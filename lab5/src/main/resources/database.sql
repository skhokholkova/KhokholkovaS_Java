-- Лабораторна робота 5. Створення структури бази даних students_db та її наповнення.
-- СУБД: H2 (сама база створюється автоматично при першому підключенні користувача lab5_admin).

DROP TABLE IF EXISTS students;

CREATE TABLE students (
    id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name          VARCHAR(50) NOT NULL,
    first_name         VARCHAR(50) NOT NULL,
    middle_name        VARCHAR(50) NOT NULL,
    birth_date         DATE        NOT NULL,
    record_book_number VARCHAR(20) NOT NULL UNIQUE
);

